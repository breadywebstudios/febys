-- =====================================================================
--  FEBYS — reviews carousel (managed in admin → Reviews)
--  Public can read shown reviews; only Febys admins can change them.
--  The seeded rows are clearly labelled samples (is_sample = true).
-- =====================================================================
create table if not exists febys.reviews (
  id bigint generated by default as identity primary key,
  reviewer text not null default 'Customer name' check (length(reviewer) <= 80),
  dish text check (dish is null or length(dish) <= 120),
  body text not null check (length(body) between 1 and 600),
  rating int not null default 5 check (rating between 1 and 5),
  photo_url text check (photo_url is null or length(photo_url) <= 500),
  is_sample boolean not null default false,
  active boolean not null default true,
  sort int not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create trigger touch before update on febys.reviews for each row execute function febys.touch_updated_at();
alter table febys.reviews enable row level security;
grant select on febys.reviews to anon, authenticated;
grant insert, update, delete on febys.reviews to authenticated;
create policy "public read shown reviews" on febys.reviews for select to anon, authenticated using (active or (select febys.is_admin()));
create policy "admins insert reviews" on febys.reviews for insert to authenticated with check ((select febys.is_admin()));
create policy "admins update reviews" on febys.reviews for update to authenticated using ((select febys.is_admin())) with check ((select febys.is_admin()));
create policy "admins delete reviews" on febys.reviews for delete to authenticated using ((select febys.is_admin()));

