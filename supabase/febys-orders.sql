-- =====================================================================
--  FEBYS — customer orders
--  Run after febys-setup.sql. Safe to run more than once.
--  Customers save orders through febys.place_order() (no direct table
--  access); only Febys admins can read, update or delete orders.
-- =====================================================================

create table if not exists febys.orders (
  id bigint generated by default as identity primary key,
  ref text not null unique,
  created_at timestamptz not null default now(),
  customer_name text not null check (length(customer_name) between 1 and 120),
  phone text not null check (length(phone) between 5 and 40),
  mode text not null check (mode in ('Delivery','Pickup')),
  address text check (address is null or length(address) <= 500),
  order_date date,
  order_time time,
  chafing boolean not null default false,
  notes text check (notes is null or length(notes) <= 1000),
  items jsonb not null check (jsonb_typeof(items) = 'array'),
  subtotal numeric(10,2) not null default 0,
  has_estimates boolean not null default false,
  status text not null default 'new' check (status in ('new','confirmed','completed','cancelled')),
  admin_note text,
  updated_at timestamptz not null default now()
);
create index if not exists orders_created on febys.orders (created_at desc);
create index if not exists orders_status on febys.orders (status, created_at desc);

drop trigger if exists touch on febys.orders;
create trigger touch before update on febys.orders for each row execute function febys.touch_updated_at();

alter table febys.orders enable row level security;
revoke all on febys.orders from anon;
grant select, update, delete on febys.orders to authenticated;

drop policy if exists "admins read orders" on febys.orders;
drop policy if exists "admins update orders" on febys.orders;
drop policy if exists "admins delete orders" on febys.orders;
create policy "admins read orders" on febys.orders for select to authenticated using ((select febys.is_admin()));
create policy "admins update orders" on febys.orders for update to authenticated using ((select febys.is_admin())) with check ((select febys.is_admin()));
create policy "admins delete orders" on febys.orders for delete to authenticated using ((select febys.is_admin()));

-- Public entry point used by the "Send order on WhatsApp" button.
create or replace function febys.place_order(p jsonb)
returns text language plpgsql security definer set search_path = ''
as $$
declare
  v_ref text := upper(left(regexp_replace(coalesce(p->>'ref',''), '[^A-Za-z0-9-]', '', 'g'), 24));
  v_items jsonb := coalesce(p->'items', '[]'::jsonb);
  v_mode text := case when p->>'mode' = 'Pickup' then 'Pickup' else 'Delivery' end;
begin
  if jsonb_typeof(v_items) <> 'array' or jsonb_array_length(v_items) = 0 then
    raise exception 'Order has no items';
  end if;
  if jsonb_array_length(v_items) > 60 or length(v_items::text) > 40000 then
    raise exception 'Order is too large';
  end if;
  if coalesce(trim(p->>'name'),'') = '' or coalesce(trim(p->>'phone'),'') = '' then
    raise exception 'Name and phone are required';
  end if;
  if v_ref = '' or exists (select 1 from febys.orders where ref = v_ref) then
    v_ref := 'FB-' || to_char(now() at time zone 'Asia/Dubai', 'MMDD') || '-' || lpad((floor(random()*1000000))::text, 6, '0');
  end if;

  insert into febys.orders (ref, customer_name, phone, mode, address, order_date, order_time, chafing, notes, items, subtotal, has_estimates)
  values (
    v_ref,
    left(trim(p->>'name'), 120),
    left(trim(p->>'phone'), 40),
    v_mode,
    nullif(left(trim(coalesce(p->>'address','')), 500), ''),
    nullif(p->>'date','')::date,
    nullif(p->>'time','')::time,
    coalesce((p->>'chafing')::boolean, false),
    nullif(left(trim(coalesce(p->>'notes','')), 1000), ''),
    v_items,
    greatest(coalesce((p->>'subtotal')::numeric, 0), 0),
    coalesce((p->>'has_estimates')::boolean, false)
  );
  return v_ref;
end; $$;

revoke all on function febys.place_order(jsonb) from public;
grant execute on function febys.place_order(jsonb) to anon, authenticated;

select 'orders ready' as status, (select count(*) from febys.orders) as orders;
