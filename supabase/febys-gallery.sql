-- =====================================================================
--  FEBYS — photo gallery (managed in admin → Gallery)
--  Stores which photos show, their category, order and captions.
--  The photos themselves are files in the website folder.
-- =====================================================================
create table if not exists febys.gallery (
  id bigint generated by default as identity primary key,
  path text not null unique check (length(path) between 1 and 300 and path !~ '^[a-z]+:' and path !~ '\.\.'),
  caption text check (caption is null or length(caption) <= 120),
  category text not null default 'food' check (category in ('food','events','catering')),
  active boolean not null default true,
  sort int not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create trigger touch before update on febys.gallery for each row execute function febys.touch_updated_at();
alter table febys.gallery enable row level security;
grant select on febys.gallery to anon, authenticated;
grant insert, update, delete on febys.gallery to authenticated;
create policy "public read shown gallery" on febys.gallery for select to anon, authenticated using (active or (select febys.is_admin()));
create policy "admins insert gallery" on febys.gallery for insert to authenticated with check ((select febys.is_admin()));
create policy "admins update gallery" on febys.gallery for update to authenticated using ((select febys.is_admin())) with check ((select febys.is_admin()));
create policy "admins delete gallery" on febys.gallery for delete to authenticated using ((select febys.is_admin()));

