-- =====================================================================
--  FEBYS — menu admin database setup
--  Run once in the new Supabase project: SQL Editor → New query → Run.
--  Creates the febys schema, tables, security rules, photo storage,
--  and copies the current menu (4 categories, 22 items) and settings.
-- =====================================================================

create schema if not exists febys;
grant usage on schema febys to anon, authenticated;

create table if not exists febys.admins (
  email text primary key check (email = lower(email)),
  name text,
  created_at timestamptz not null default now()
);

create or replace function febys.is_admin()
returns boolean language sql stable security definer set search_path = ''
as $$
  select exists (select 1 from febys.admins a
                 where a.email = lower(coalesce(auth.jwt() ->> 'email', '')));
$$;

create or replace function febys.touch_updated_at()
returns trigger language plpgsql set search_path = ''
as $$ begin new.updated_at := now(); return new; end; $$;

create table if not exists febys.categories (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  note text,
  sort int not null default 0,
  active boolean not null default true,
  updated_at timestamptz not null default now()
);

create table if not exists febys.menu_items (
  id bigint generated by default as identity primary key,
  category_id bigint not null references febys.categories(id) on delete restrict,
  name text not null,
  pax text,
  description text,
  includes text[] not null default '{}',
  price numeric(10,2) check (price is null or price >= 0),
  variants jsonb not null default '[]'::jsonb check (jsonb_typeof(variants) = 'array'),
  badge text,
  photo_url text,
  tone text not null default 'g1' check (tone in ('g1','g2','g3','g4')),
  sort int not null default 0,
  active boolean not null default true,
  updated_at timestamptz not null default now()
);
create index if not exists menu_items_category_sort on febys.menu_items (category_id, sort);

create table if not exists febys.settings (
  id int primary key default 1 check (id = 1),
  whatsapp text not null default '971563267346',
  notice_on boolean not null default true,
  notice_title text not null default 'Holiday Packages',
  notice_text text not null default 'are back — available every day. Advance booking required.',
  footnote text not null default 'Prices exclude delivery charges. Chafing dish rental is charged separately. Pricing is subject to change based on availability.',
  updated_at timestamptz not null default now()
);

drop trigger if exists touch on febys.categories;
drop trigger if exists touch on febys.menu_items;
drop trigger if exists touch on febys.settings;
create trigger touch before update on febys.categories for each row execute function febys.touch_updated_at();
create trigger touch before update on febys.menu_items for each row execute function febys.touch_updated_at();
create trigger touch before update on febys.settings for each row execute function febys.touch_updated_at();

alter table febys.admins enable row level security;
alter table febys.categories enable row level security;
alter table febys.menu_items enable row level security;
alter table febys.settings enable row level security;

grant select on febys.categories, febys.menu_items, febys.settings to anon, authenticated;
grant insert, update, delete on febys.categories, febys.menu_items to authenticated;
grant update on febys.settings to authenticated;
grant select, insert, delete on febys.admins to authenticated;
grant usage, select on all sequences in schema febys to authenticated;

drop policy if exists "public read active categories" on febys.categories;
drop policy if exists "admins insert categories" on febys.categories;
drop policy if exists "admins update categories" on febys.categories;
drop policy if exists "admins delete categories" on febys.categories;
create policy "public read active categories" on febys.categories for select to anon, authenticated using (active or (select febys.is_admin()));
create policy "admins insert categories" on febys.categories for insert to authenticated with check ((select febys.is_admin()));
create policy "admins update categories" on febys.categories for update to authenticated using ((select febys.is_admin())) with check ((select febys.is_admin()));
create policy "admins delete categories" on febys.categories for delete to authenticated using ((select febys.is_admin()));

drop policy if exists "public read active items" on febys.menu_items;
drop policy if exists "admins insert items" on febys.menu_items;
drop policy if exists "admins update items" on febys.menu_items;
drop policy if exists "admins delete items" on febys.menu_items;
create policy "public read active items" on febys.menu_items for select to anon, authenticated using (active or (select febys.is_admin()));
create policy "admins insert items" on febys.menu_items for insert to authenticated with check ((select febys.is_admin()));
create policy "admins update items" on febys.menu_items for update to authenticated using ((select febys.is_admin())) with check ((select febys.is_admin()));
create policy "admins delete items" on febys.menu_items for delete to authenticated using ((select febys.is_admin()));

drop policy if exists "public read settings" on febys.settings;
drop policy if exists "admins update settings" on febys.settings;
create policy "public read settings" on febys.settings for select to anon, authenticated using (true);
create policy "admins update settings" on febys.settings for update to authenticated using ((select febys.is_admin())) with check ((select febys.is_admin()));

drop policy if exists "admins read admins" on febys.admins;
drop policy if exists "admins add admins" on febys.admins;
drop policy if exists "admins remove other admins" on febys.admins;
create policy "admins read admins" on febys.admins for select to authenticated using ((select febys.is_admin()));
create policy "admins add admins" on febys.admins for insert to authenticated with check ((select febys.is_admin()));
create policy "admins remove other admins" on febys.admins for delete to authenticated
  using ((select febys.is_admin()) and email <> lower(coalesce(auth.jwt() ->> 'email', '')));

